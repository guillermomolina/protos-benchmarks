from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from runner.perf009a import ROOT, materialize_inventory

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, help="optional JSON output path; stdout is used when omitted")
    args = parser.parse_args()
    inventory = materialize_inventory(ROOT / ".work" / "perf009a" / "a1-source")
    payload = json.dumps(inventory, indent=2, sort_keys=True) + "\n"
    if args.output is None:
        print(payload, end="")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload, encoding="utf-8")
        print(f"PERF009_A1_INVENTORY={args.output}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())

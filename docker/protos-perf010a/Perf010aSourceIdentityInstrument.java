import com.oracle.truffle.api.instrumentation.Instrumenter;
import com.oracle.truffle.api.instrumentation.LoadSourceSectionEvent;
import com.oracle.truffle.api.instrumentation.SourceSectionFilter;
import com.oracle.truffle.api.instrumentation.TruffleInstrument;
import com.oracle.truffle.api.nodes.RootNode;
import com.oracle.truffle.api.source.SourceSection;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import org.graalvm.options.OptionCategory;
import org.graalvm.options.OptionDescriptor;
import org.graalvm.options.OptionDescriptors;
import org.graalvm.options.OptionKey;
import org.graalvm.options.OptionStability;

/**
 * PERF010-A / #691 caller/helper source-identity diagnostic (harness-local, not published to
 * {@code guillermomolina/protos}).
 *
 * <p>The retained PERF010-A caller/helper compiler-lifecycle trace
 * (guillermomolina/protos-project-docs@29a38fd3c0fb2f10a1fb5dc4a6a4616e05abe98e,
 * {@code PERF010-A_CALLER_HELPER_TRACE_SOURCE_IDENTITY_BLOCKER.md}) established that every
 * traced compilation event reported {@code Src n/a} because, at the pinned Protos revision, the
 * generated Bytecode DSL roots for a guest module (both the untagged
 * {@code ProtosBytecodeRootNode} "helper" root and the {@code ProtosSemanticBytecodeRootNode}
 * "semantic" wrapper root {@code InvokeSemanticHelper} calls) are created with
 * {@code BytecodeConfig.DEFAULT}, which does not materialize optional source information at
 * parse time. Protos' own {@code ProtosPerf006B5BSourceInstrumentationLocationTest} already
 * proves the established, intended materialization mechanism for this exact situation: attaching
 * real Truffle instrumentation forces the Bytecode DSL to reparse the affected root node group
 * with source information included, in place, without discarding {@code CallTarget} identity or
 * changing guest-observable semantics.
 *
 * <p>This class reuses exactly that mechanism from the harness side, through public Truffle
 * instrumentation API only ({@code Instrumenter#attachLoadSourceSectionListener}) - it never
 * reaches into {@code com.guillermomolina.protos} internals, never touches
 * {@code BytecodeConfig.DEFAULT} in Protos source, and is otherwise inert: with its option left
 * at the default (disabled), attaching or not attaching this instrument has no effect on any
 * other PERF010-A command (reference/smoke, any ablation), because Truffle only instantiates a
 * registered instrument when something explicitly enables it.
 *
 * <p>Scope is deliberately narrow: the attached listener's {@link SourceSectionFilter} matches
 * only sources literally named {@code method-call.protos} (the PERF010-A
 * {@code micro/method-call} workload's own Source name, set by
 * {@code Source.newBuilder(..., sourcePath.getFileName().toString())} in every PERF010-A
 * driver), so this diagnostic cannot make unrelated Standard Library/module roots
 * source-visible while leaving the target caller un-correlated, and cannot silently widen into a
 * general "materialize everything" mechanism.
 *
 * <p>Enabled only via the standard GraalVM polyglot option convention for a single boolean
 * instrument option named after its own id (matching, e.g., {@code --cpusampler}): passing
 * {@code -Dpolyglot.perf010aSourceIdentity=true} (or the engine-builder equivalent) on the same
 * {@code java} invocation already used for every other PERF010-A diagnostic/timing command is
 * sufficient; no driver code change is required to opt in.
 *
 * <p>Discovered via a hand-written {@link Perf010aSourceIdentityInstrumentProvider} registered
 * under {@code META-INF/services}, matching the exact SPI shape Truffle's own
 * {@code @TruffleInstrument.Registration} annotation processor would otherwise generate (see
 * that class's javadoc); no annotation processor runs as part of this harness's plain
 * {@code javac} diagnostic-driver compilation step. The engine reads id/name/version metadata
 * from the {@code @Registration} annotation on that Provider class itself, not from this class,
 * even though this class carries an identical copy for its own readability - see the Provider
 * class's javadoc for the empirical confirmation.
 */
@TruffleInstrument.Registration(
        id = Perf010aSourceIdentityInstrument.ID,
        name = "PERF010-A Caller/Helper Source Identity Diagnostic",
        version = "1.0")
public final class Perf010aSourceIdentityInstrument extends TruffleInstrument {

    /** Also this instrument's boolean enable-option name (matches the single-option pattern). */
    public static final String ID = "perf010aSourceIdentity";

    /**
     * The exact PERF010-A {@code micro/method-call} workload Source name; see class javadoc for
     * why this diagnostic is deliberately scoped to only this one Source.
     */
    public static final String TARGET_SOURCE_NAME = "method-call.protos";

    private static final OptionKey<Boolean> ENABLED = new OptionKey<>(false);

    private static final List<SourceRecord> OBSERVED =
            Collections.synchronizedList(new ArrayList<>());

    /** One materialized source section observed for {@link #TARGET_SOURCE_NAME}. */
    public record SourceRecord(
            String sourceName,
            int startOffset,
            int endOffset,
            int length,
            int line,
            int columnOneBased,
            String text,
            String rootNodeClassName) {
    }

    /** Snapshot of every source section this instrument has observed so far, in load order. */
    public static List<SourceRecord> observedRecords() {
        synchronized (OBSERVED) {
            return List.copyOf(OBSERVED);
        }
    }

    /** Clears prior observations; called by a smoke/diagnostic driver before its own measured run. */
    public static void resetForNewMeasurement() {
        synchronized (OBSERVED) {
            OBSERVED.clear();
        }
    }

    @Override
    protected OptionDescriptors getOptionDescriptors() {
        return OptionDescriptors.create(
                List.of(
                        OptionDescriptor.newBuilder(ENABLED, ID)
                                .category(OptionCategory.USER)
                                // STABLE, not EXPERIMENTAL: this is our own diagnostic option,
                                // not an unstable Truffle feature. EXPERIMENTAL requires the
                                // embedder to call allowExperimentalOptions(true) on the
                                // Context/Engine builder - confirmed empirically ("Option
                                // 'perf010aSourceIdentity' is experimental and must be enabled
                                // with allowExperimentalOptions(...)") - which would mean
                                // touching ProtosPolyglotExecutionContext.open()'s
                                // Context.newBuilder() call, a Protos-internal class this
                                // diagnostic must not modify.
                                .stability(OptionStability.STABLE)
                                .help(
                                        "PERF010-A / #691 diagnostic: force Bytecode DSL source-section "
                                                + "materialization for the "
                                                + TARGET_SOURCE_NAME
                                                + " caller/helper roots by attaching a Truffle "
                                                + "instrumentation listener scoped to that one Source. "
                                                + "Diagnostic-only; never used by PERF010-A reference or "
                                                + "smoke timing evidence.")
                                .build()));
    }

    @Override
    protected void onCreate(Env env) {
        Instrumenter instrumenter = env.getInstrumenter();
        SourceSectionFilter filter =
                SourceSectionFilter.newBuilder()
                        .sourceIs(source -> source != null && TARGET_SOURCE_NAME.equals(source.getName()))
                        .build();
        instrumenter.attachLoadSourceSectionListener(
                filter,
                (LoadSourceSectionEvent event) -> {
                    SourceSection section = event.getSourceSection();
                    if (section == null || !section.isAvailable()) {
                        return;
                    }
                    RootNode rootNode = event.getNode() == null ? null : event.getNode().getRootNode();
                    OBSERVED.add(
                            new SourceRecord(
                                    section.getSource().getName(),
                                    section.getCharIndex(),
                                    section.getCharIndex() + section.getCharLength(),
                                    section.getCharLength(),
                                    section.getStartLine(),
                                    section.getStartColumn(),
                                    section.getCharacters().toString(),
                                    rootNode == null ? "unknown" : rootNode.getClass().getName()));
                },
                true);
    }
}
